using System.Text.Json;
using Zodiac.Framework;
using Zodiac.Framework.Tests.Fixtures;
using Xunit;
using Tessera.Engine;

namespace Zodiac.Framework.Tests;

public sealed class RandomReplayRunnerTests
{
    [Fact]
    public void Committed_bios_sequences_replay_all_64_draws_in_order()
    {
        using JsonDocument fixture = JsonDocument.Parse(File.ReadAllText(
            Path.Combine(AppContext.BaseDirectory, "Fixtures", "scph5501-rng-vectors.json")));
        int total = 0;
        foreach (JsonElement sequence in fixture.RootElement.GetProperty("cases").EnumerateArray())
        {
            var expected = sequence.GetProperty("draws").EnumerateArray().Select(draw =>
                new RandomDraw<FftRandomState>(new FftRandomState(draw.GetProperty("stateAfter").GetUInt32(),
                    draw.GetProperty("draw").GetUInt64()), draw.GetProperty("value").GetUInt32())).ToArray();
            RandomReplayRunner.Report report = RandomReplayRunner.Run(
                FftBiosRandom.Seed(sequence.GetProperty("seed").GetUInt32()), expected);
            Assert.True(report.Passed, sequence.GetProperty("caseId").GetString() + ": " + report.Diagnostic);
            Assert.Null(report.DrawIndex);
            Assert.Null(report.Field);
            total += expected.Length;
        }
        Assert.Equal(64, total);
    }

    [Theory]
    [InlineData("state.value")]
    [InlineData("value")]
    [InlineData("state.drawCount")]
    public void Changed_second_draw_reports_first_mismatched_draw_and_field(string field)
    {
        // Recorded seed-one observations, not expectations generated by the implementation under test.
        RandomDraw<FftRandomState>[] expected = SeedOne();
        RandomDraw<FftRandomState> second = expected[1];
        expected[1] = field switch
        {
            "state.value" => second with { State = second.State with { Value = second.State.Value ^ 1u } },
            "value" => second with { Value = second.Value ^ 1u },
            _ => second with { State = second.State with { DrawCount = second.State.DrawCount + 1 } },
        };
        RandomReplayRunner.Report report = RandomReplayRunner.Run(FftBiosRandom.Seed(1), expected);
        Assert.False(report.Passed);
        Assert.Equal(1, report.DrawIndex);
        Assert.Equal(field, report.Field);
        Assert.Contains("draw 2", report.Diagnostic);
        Assert.Contains("expected", report.Diagnostic);
        Assert.Contains("actual", report.Diagnostic);
    }

    [Fact]
    public void Multiple_differences_report_earliest_draw_and_first_field()
    {
        RandomDraw<FftRandomState>[] expected = SeedOne();
        expected[0] = new(new(0, 9), 1);
        expected[1] = new(new(0, 9), 1);
        RandomReplayRunner.Report report = RandomReplayRunner.Run(FftBiosRandom.Seed(1), expected);
        Assert.False(report.Passed);
        Assert.Equal(0, report.DrawIndex);
        Assert.Equal("state.value", report.Field);
        Assert.Contains("draw 1", report.Diagnostic);
    }

    [Fact]
    public void Replaying_identical_expected_transitions_is_repeatable_and_does_not_mutate_inputs()
    {
        var initial = FftBiosRandom.Seed(1);
        RandomDraw<FftRandomState>[] expected = SeedOne();
        RandomDraw<FftRandomState>[] snapshot = expected.ToArray();
        var first = RandomReplayRunner.Run(initial, expected);
        Assert.True(first.Passed, first.Diagnostic);
        Assert.Equal(first, RandomReplayRunner.Run(initial, expected));
        Assert.Equal(new FftRandomState(1, 0), initial);
        Assert.Equal(snapshot, expected);
    }

    private static RandomDraw<FftRandomState>[] SeedOne() =>
    [
        new(new(1103527590u, 1), 16838u),
        new(new(2524885223u, 2), 5758u),
        new(new(662824084u, 3), 10113u),
    ];
}
