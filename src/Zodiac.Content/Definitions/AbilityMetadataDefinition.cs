using System.Collections.Immutable;
using Zodiac.Framework.Ai;

namespace Zodiac.Content.Definitions;

/// <summary>Immutable learning and semantic AI metadata; this definition does not supply an executable combat effect.</summary>
public sealed class AbilityMetadataDefinition
{
    public AbilityId Id { get; }
    public int JpCost { get; }
    public int LearnOnHitRateRaw { get; }
    /// <summary>Original serialized classification, not an executable effect or the ID-range classification.</summary>
    public int SerializedClassRaw { get; }
    public bool LearnOnHit { get; }
    public bool ShowName { get; }
    public bool CanLearnWithJp { get; }
    /// <summary>Unresolved original bit 4, preserved without assigning it gameplay meaning.</summary>
    public bool UnknownTypeBit4 { get; }
    /// <summary>Compatibility export view generated from the semantic definition; not an editable configuration source.</summary>
    public ImmutableArray<byte> AiFlagsRaw { get; }
    public AiAbilityBehavior AiBehavior { get; }
    public bool UsableByAi { get; }
    /// <summary>Original static bit, deliberately separate from runtime consume-aim policy.</summary>
    public bool AiEvadeWithMotion { get; }
    /// <summary>Only unresolved original static bits; known usable/motion bits are authored separately.</summary>
    public byte UnresolvedAiBitsRaw { get; }
    public bool HasUnresolvedAiFlags => UnresolvedAiBitsRaw != 0;

    /// <summary>Author readable immutable AI behavior. Original packing is generated by the compatibility adapter.</summary>
    public AbilityMetadataDefinition(AbilityId id, int jpCost, int learnOnHitRateRaw, int serializedClassRaw,
        AiAbilityBehavior aiBehavior, bool usableByAi, bool aiEvadeWithMotion = false, byte unresolvedAiBitsRaw = 0,
        bool learnOnHit = false, bool showName = false, bool canLearnWithJp = true, bool unknownTypeBit4 = false)
    {
        DefinitionValidation.RequiredId(id.Value, nameof(id));
        DefinitionValidation.Range(jpCost, ushort.MaxValue, nameof(jpCost));
        DefinitionValidation.Range(learnOnHitRateRaw, byte.MaxValue, nameof(learnOnHitRateRaw));
        DefinitionValidation.Range(serializedClassRaw, 15, nameof(serializedClassRaw));
        ArgumentNullException.ThrowIfNull(aiBehavior);
        if ((aiBehavior.AreaShape & ~(AiAbilityAreaShape.TripleBracelet | AiAbilityAreaShape.TripleAttack | AiAbilityAreaShape.Cone | AiAbilityAreaShape.Linear)) != 0)
            throw new ArgumentOutOfRangeException(nameof(aiBehavior), "Unknown semantic area-shape value.");
        OriginalAbilityAiFlags.ValidateUnresolved(unresolvedAiBitsRaw);
        Id = id; JpCost = jpCost; LearnOnHitRateRaw = learnOnHitRateRaw; SerializedClassRaw = serializedClassRaw;
        LearnOnHit = learnOnHit; ShowName = showName; CanLearnWithJp = canLearnWithJp; UnknownTypeBit4 = unknownTypeBit4;
        AiBehavior = aiBehavior; UsableByAi = usableByAi; AiEvadeWithMotion = aiEvadeWithMotion; UnresolvedAiBitsRaw = unresolvedAiBitsRaw;
        AiFlagsRaw = OriginalAbilityAiFlags.Encode(aiBehavior, usableByAi, aiEvadeWithMotion, unresolvedAiBitsRaw);
    }

    /// <summary>Compatibility constructor for existing raw-byte callers. Prefer semantic behavior for authored definitions.</summary>
    public AbilityMetadataDefinition(AbilityId id, int jpCost, int learnOnHitRateRaw, int serializedClassRaw,
        IEnumerable<byte> aiFlagsRaw, bool learnOnHit = false, bool showName = false,
        bool canLearnWithJp = true, bool unknownTypeBit4 = false)
        : this(id, jpCost, learnOnHitRateRaw, serializedClassRaw, OriginalAbilityAiFlags.Read(aiFlagsRaw), learnOnHit, showName, canLearnWithJp, unknownTypeBit4) { }

    private AbilityMetadataDefinition(AbilityId id, int cost, int rate, int serializedClass, OriginalAbilityAiFlags.Fields fields,
        bool learn, bool show, bool canLearn, bool unknown)
        : this(id, cost, rate, serializedClass, fields.Behavior, fields.Usable, fields.Motion, fields.Unresolved, learn, show, canLearn, unknown) { }

    /// <summary>Read a preserved original record at an import or legacy-package boundary.</summary>
    public static AbilityMetadataDefinition FromOriginalAiFlags(AbilityId id, int jpCost, int learnOnHitRateRaw, int serializedClassRaw,
        IEnumerable<byte> aiFlagsRaw, bool learnOnHit = false, bool showName = false,
        bool canLearnWithJp = true, bool unknownTypeBit4 = false) =>
        new(id, jpCost, learnOnHitRateRaw, serializedClassRaw, OriginalAbilityAiFlags.Read(aiFlagsRaw), learnOnHit, showName, canLearnWithJp, unknownTypeBit4);
}
